def seed_all(conn):
    for p in PRODUCTS:
        shops = p.pop("shops")
        conn.execute(
            """INSERT INTO products
               (id, name, brand, category, volume_ml, time_of_day, skin_types, concerns, actives, description, popularity, icon)
               VALUES (?,?,?,?,?,?,?,?,?,?,?,?)""",
            (
                p["id"], p["name"], p["brand"], p["category"], p["volume_ml"], p["time_of_day"],
                json.dumps(p["skin_types"], ensure_ascii=False),
                json.dumps(p["concerns"], ensure_ascii=False),
                json.dumps(p["actives"], ensure_ascii=False),
                p["description"], p["popularity"], p["icon"],
            ),
        )
        for shop_name, price in shops.items():
            conn.execute(
                """INSERT INTO shop_prices (product_id, shop_name, price, url, updated_at, source)
                   VALUES (?,?,?,?,?,?)""",
                (p["id"], shop_name, price, None, NOW, "seed"),
            )
